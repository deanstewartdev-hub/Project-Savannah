// Builds the shot-selection report for the first Chefchaouen video.
//
// Read-only: it searches Pexels (free, no render, no upload) with the same planner the worker
// uses, then writes SHOT_SELECTION.md next to this file. It also checks that every narration
// line in shot-plan.json appears verbatim in the approved script source, so the report cannot
// drift from the approved wording.
//
// Usage (owner or agent with the Pexels key in the environment):
//   PEXELS_API_KEY=... node tools/first-video/shot-selection.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { planBeatVisuals, segmentLengths } from "../../media-worker/src/pipeline/visualSelection.js";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const plan = JSON.parse(readFileSync(join(here, "shot-plan.json"), "utf8"));
const approvedSource = readFileSync(join(repo, "Scripts", "Script_Revision_Maintenance.js"), "utf8");

const key = process.env.PEXELS_API_KEY;
if (!key) {
  console.error("PEXELS_API_KEY is not set.");
  process.exit(1);
}

// Narration must match the approved script exactly.
const narrationMismatches = plan.scenes.filter((scene) => !approvedSource.includes(scene.narration));
if (narrationMismatches.length > 0) {
  console.error("Narration differs from the approved script for scenes:", narrationMismatches.map((s) => s.sceneNumber));
  process.exit(2);
}

async function search(query) {
  const url = new URL("https://api.pexels.com/videos/search");
  url.searchParams.set("query", query);
  url.searchParams.set("orientation", "portrait");
  url.searchParams.set("size", "medium");
  url.searchParams.set("per_page", "8");
  const response = await fetch(url, { headers: { Authorization: key } });
  if (!response.ok) throw new Error("Pexels search failed (" + response.status + ")");
  const data = await response.json();
  return data.videos || [];
}

// Beat durations are estimated from the probed length of the last render (42.27 s) split by
// word count. The real split comes from Whisper alignment at render time, so this is a planning
// estimate; the report shows it so the shot list can be checked against the real timing later.
const probedSeconds = 42.27;
const wordCounts = plan.scenes.map((scene) => scene.narration.split(/\s+/).filter(Boolean).length);
const totalWords = wordCounts.reduce((a, b) => a + b, 0);
const crossfade = 0.4;
const beats = plan.scenes.map((scene, index) => ({
  text: scene.narration,
  visualQuery: scene.searchKeywords,
  imagePrompt: scene.searchKeywords,
  location: scene.location,
  searchKeywords: scene.searchKeywords,
  estimatedSeconds: probedSeconds * wordCounts[index] / totalWords,
  coverSeconds: probedSeconds * wordCounts[index] / totalWords + (index < plan.scenes.length - 1 ? crossfade : 0)
}));
// Allow AI stills here only so every scene is reported. Stills are listed as coverage gaps,
// never as footage.
const chosen = await planBeatVisuals(beats, search, { allowAiStills: true });

const lines = [];
lines.push("# Shot selection: Chefchaouen first video");
lines.push("");
lines.push("Generated by `tools/first-video/shot-selection.mjs` from live Pexels search results (read-only).");
lines.push("Narration checked against the approved script: all " + plan.scenes.length + " lines match.");
lines.push("");
lines.push("**Pexels metadata is supporting evidence only.** A title or uploader name that mentions Chefchaouen does not prove the footage was filmed there. Every clip below needs a human look before the render is approved.");
lines.push("");

let gaps = 0;
for (const entry of chosen) {
  const scene = plan.scenes[entry.beatIndex];
  lines.push("## Scene " + scene.sceneNumber);
  lines.push("");
  lines.push("- Narration: " + scene.narration);
  lines.push("- Search fields: place `" + scene.location + "`, keywords `" + scene.searchKeywords + "`");
  lines.push("- Queries tried, in order: " + entry.queriesTried.map((q) => "`" + q + "`").join(", "));
  if (entry.type === "video") {
    lines.push("- Estimated beat length: " + beats[entry.beatIndex].estimatedSeconds.toFixed(1) + " s (cover " + beats[entry.beatIndex].coverSeconds.toFixed(1) + " s with crossfade)");
    // Same piece lengths the assembler uses (media-worker assemble.js via segmentLengths).
    const lengths = segmentLengths(entry.segments.map((s) => s.sourceDurationSeconds), beats[entry.beatIndex].coverSeconds);
    let cursor = 0;
    entry.segments.forEach((segment, k) => {
      const length = lengths[k];
      lines.push("- Cut " + (k + 1) + " (" + cursor.toFixed(1) + "-" + (cursor + length).toFixed(1) + " s, " + length.toFixed(1) + " s of a " + segment.sourceDurationSeconds + " s clip): [Pexels " + segment.pexelsId + "](" + segment.sourceUrl + "), query `" + segment.query + "`");
      lines.push("  - Relevance: " + segment.reason);
      cursor += length;
    });
    lines.push("- Human review: **pending**");
  } else {
    gaps += 1;
    lines.push("- **Visual-coverage gap:** no relevant footage passed the gate. A labelled AI illustration would be used only if you allow it; it is not authentic footage.");
  }
  lines.push("");
}

lines.push("## Summary");
lines.push("");
lines.push("- Scenes with a chosen clip: " + (chosen.length - gaps) + " of " + chosen.length);
lines.push("- Coverage gaps: " + gaps);
lines.push("- GO/NO-GO for a second render: see the recommendation in the handover note, not this file.");
lines.push("");

const out = join(here, "SHOT_SELECTION.md");
writeFileSync(out, lines.join("\n"));
console.log("Wrote " + out + " (" + (chosen.length - gaps) + " clips, " + gaps + " gaps)");
